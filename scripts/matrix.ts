import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type {
  MatrixCell,
  MatrixFeature,
  MatrixReport,
} from "../tests/matrix/matrix-report";
import { MATRIX_JSON_PATH } from "../tests/matrix/matrix-report";
import { PROVIDER_PATHS, type Provider } from "../src/transformers";

/**
 * `npm run matrix` (v1.5 spec §3.4, Task 11): renders
 * `tests/matrix/.out/matrix.json` — written by the pair tests'
 * teardown — into `docs/compatibility.md`. `--check` regenerates in
 * memory and exits 1 with a unified diff when the committed file's
 * cells differ; header/body text outside the cells never fails, so a
 * badge or link refresh cannot make CI red by itself.
 */

const ROOT = join(__dirname, "..");
const DOC_PATH = join(ROOT, "docs", "compatibility.md");

// Providers come from the adapter registry the pair tests iterate —
// adding a provider grows the tables in lockstep.
const PROVIDERS = Object.keys(PROVIDER_PATHS) as Provider[];

const FEATURES: { key: MatrixFeature; title: string }[] = [
  { key: "plain", title: "Plain request" },
  { key: "stream", title: "Streaming" },
  { key: "tools", title: "Tool calls" },
  { key: "stream_tools", title: "Tool calls (streaming)" },
  { key: "structured", title: "Structured output" },
  { key: "reasoning", title: "Reasoning" },
  { key: "url_image", title: "URL image" },
  { key: "document", title: "Document (PDF)" },
  { key: "tool_image", title: "Image in a tool result" },
  { key: "passthrough", title: "Same-format pass-through" },
];

function cellText(cell: MatrixCell | undefined): string {
  if (cell === undefined) return "—";
  if (cell.status === "pass") return "✓";
  if (cell.status === "note") return `✓ ${cell.note ?? "note"}`;
  return `✗ ${cell.note ?? "fail"}`;
}

export function renderMatrix(report: MatrixReport): string {
  const lines: string[] = [
    "# Compatibility matrix",
    "",
    // The badge tracks the scheduled client-replay job only
    // (`?event=schedule`), so a new client release's failure is
    // visible here without reddening every push to main (spec §3.4,
    // conductor's call).
    "![client replay](https://github.com/dorrabbkhan/babelgate/actions/workflows/live.yml/badge.svg?event=schedule)",
    "",
    "Latest client replay run: <https://github.com/dorrabbkhan/babelgate/actions/workflows/live.yml> — its summary lists the replayed client versions.",
    "",
    "Generated by `npm run matrix` from the pair tests (`tests/matrix/.out/matrix.json`). Do not edit by hand — CI regenerates it and fails on drift.",
    "",
    "Rows are the client (source) dialect, columns the upstream (target) provider. `✓` works; `✓ note` works with a caveat; `✗ reason` fails; `—` no cell recorded.",
    "",
  ];
  for (const { key, title } of FEATURES) {
    lines.push(`## ${title} (\`${key}\`)`, "");
    lines.push(
      `| source \\ target | ${PROVIDERS.join(" | ")} |`,
      `| --- | ${PROVIDERS.map(() => "---").join(" | ")} |`,
    );
    for (const source of PROVIDERS) {
      const cells = PROVIDERS.map((target) =>
        cellText(report.cells[key]?.[source]?.[target]),
      );
      lines.push(`| ${source} | ${cells.join(" | ")} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

// ---------- --check ----------

type CellKey = string;
type CellMap = Map<CellKey, { status: string; note?: string }>;

/** Re-parse a rendered/compatibility.md table region into cells. */
function parseCells(markdown: string): CellMap {
  const cells: CellMap = new Map();
  let feature: string | undefined;
  for (const line of markdown.split("\n")) {
    const heading = /^## .+\(`([a-z_]+)`\)\s*$/.exec(line);
    if (heading) {
      feature = heading[1];
      continue;
    }
    if (feature === undefined || !line.startsWith("|")) continue;
    const fields = line
      .split("|")
      .slice(1, -1)
      .map((f) => f.trim());
    const source = fields[0];
    if (
      source === "source \\ target" ||
      source === "---" ||
      fields.length !== PROVIDERS.length + 1
    ) {
      continue;
    }
    for (const [i, text] of fields.slice(1).entries()) {
      const target = PROVIDERS[i]!;
      if (text === "—" || text === "") continue;
      if (text.startsWith("✓ ")) {
        cells.set(`${feature}|${source}|${target}`, {
          status: "note",
          note: text.slice(2),
        });
      } else if (text === "✓") {
        cells.set(`${feature}|${source}|${target}`, { status: "pass" });
      } else if (text.startsWith("✗ ")) {
        cells.set(`${feature}|${source}|${target}`, {
          status: "fail",
          note: text.slice(2),
        });
      } else if (text === "✗") {
        cells.set(`${feature}|${source}|${target}`, { status: "fail" });
      }
    }
  }
  return cells;
}

function reportCells(report: MatrixReport): CellMap {
  const cells: CellMap = new Map();
  for (const { key } of FEATURES) {
    for (const source of PROVIDERS) {
      for (const target of PROVIDERS) {
        const cell = report.cells[key]?.[source]?.[target];
        if (cell === undefined) continue;
        cells.set(`${key}|${source}|${target}`, {
          status: cell.status,
          note: cell.note,
        });
      }
    }
  }
  return cells;
}

function cellsEqual(a: CellMap, b: CellMap): boolean {
  if (a.size !== b.size) return false;
  for (const [key, cell] of a) {
    const other = b.get(key);
    if (other === undefined) return false;
    if (other.status !== cell.status || other.note !== cell.note) {
      return false;
    }
  }
  return true;
}

/** Minimal unified diff (LCS over lines, 3 lines of context). */
export function unifiedDiff(
  oldText: string,
  newText: string,
  oldName: string,
  newName: string,
): string {
  const o = oldText.split("\n");
  const n = newText.split("\n");
  const dp: number[][] = Array.from({ length: o.length + 1 }, () =>
    new Array<number>(n.length + 1).fill(0),
  );
  for (let i = o.length - 1; i >= 0; i--) {
    for (let j = n.length - 1; j >= 0; j--) {
      dp[i]![j] =
        o[i] === n[j]
          ? dp[i + 1]![j + 1]! + 1
          : Math.max(dp[i + 1]![j]!, dp[i]![j + 1]!);
    }
  }
  type Op = { t: " " | "-" | "+"; s: string };
  const ops: Op[] = [];
  let i = 0;
  let j = 0;
  while (i < o.length && j < n.length) {
    if (o[i] === n[j]) {
      ops.push({ t: " ", s: o[i]! });
      i++;
      j++;
    } else if (dp[i + 1]![j]! >= dp[i]![j + 1]!) {
      ops.push({ t: "-", s: o[i]! });
      i++;
    } else {
      ops.push({ t: "+", s: n[j]! });
      j++;
    }
  }
  while (i < o.length) ops.push({ t: "-", s: o[i++]! });
  while (j < n.length) ops.push({ t: "+", s: n[j++]! });

  // Group changes into hunks with 3 lines of context.
  const CONTEXT = 3;
  const out: string[] = [`--- ${oldName}`, `+++ ${newName}`];
  let idx = 0;
  while (idx < ops.length) {
    while (idx < ops.length && ops[idx]!.t === " ") idx++;
    if (idx >= ops.length) break;
    const start = Math.max(0, idx - CONTEXT);
    let end = idx;
    let lastChange = idx;
    while (end < ops.length) {
      if (ops[end]!.t !== " ") lastChange = end;
      if (end - lastChange > CONTEXT * 2) break;
      end++;
    }
    const stop = Math.min(ops.length, lastChange + CONTEXT + 1);
    const hunk = ops.slice(start, stop);
    const oldCount = hunk.filter((o2) => o2.t !== "+").length;
    const newCount = hunk.filter((o2) => o2.t !== "-").length;
    let oldLine = 1;
    let newLine = 1;
    for (let k = 0; k < start; k++) {
      if (ops[k]!.t !== "+") oldLine++;
      if (ops[k]!.t !== "-") newLine++;
    }
    out.push(`@@ -${oldLine},${oldCount} +${newLine},${newCount} @@`);
    for (const op of hunk) out.push(`${op.t}${op.s}`);
    idx = stop;
  }
  return out.join("\n");
}

/**
 * Compare committed file cells against the report's. Returns the
 * unified diff of the two documents when cells differ, null
 * otherwise — text outside the cells is never compared, so a
 * badge/link/title refresh alone can't fail the gate.
 */
export function cellsDiff(
  committed: string,
  report: MatrixReport,
  rendered: string,
): string | null {
  if (cellsEqual(parseCells(committed), reportCells(report))) {
    return null;
  }
  return unifiedDiff(
    committed,
    rendered,
    "docs/compatibility.md (committed)",
    "docs/compatibility.md (regenerated)",
  );
}

export interface MatrixPaths {
  report: string;
  doc: string;
}

export const DEFAULT_PATHS: MatrixPaths = {
  report: MATRIX_JSON_PATH,
  doc: DOC_PATH,
};

export function run(
  argv: string[],
  paths: MatrixPaths = DEFAULT_PATHS,
  out: (line: string) => void = (line) => process.stdout.write(line + "\n"),
): number {
  const check = argv.includes("--check");
  let report: MatrixReport;
  try {
    report = JSON.parse(
      readFileSync(paths.report, "utf8"),
    ) as MatrixReport;
  } catch {
    out(
      `cannot read ${paths.report} — run \`npm test\` first (the pair tests' teardown writes it)`,
    );
    return 1;
  }
  const rendered = renderMatrix(report);
  if (!check) {
    writeFileSync(paths.doc, rendered);
    out(`wrote ${paths.doc}`);
    return 0;
  }
  let committed: string;
  try {
    committed = readFileSync(paths.doc, "utf8");
  } catch {
    out(`cannot read ${paths.doc} — run \`npm run matrix\` and commit the result`);
    return 1;
  }
  const diff = cellsDiff(committed, report, rendered);
  if (diff === null) {
    out("docs/compatibility.md is up to date");
    return 0;
  }
  out("docs/compatibility.md cells differ from the test report:");
  out(diff);
  return 1;
}

